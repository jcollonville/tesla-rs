-- tesla-logger archive.
-- Distances are kilometres, speeds are kilometres per hour, temperatures are
-- Celsius, energy is kilowatt-hours, power is kilowatts, and elevation is metres.
-- positions is range-partitioned by month. There is no TimescaleDB dependency.

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vin TEXT NOT NULL UNIQUE,
    tesla_id BIGINT,
    legacy_vehicle_id BIGINT,
    name TEXT,
    model TEXT,
    trim_badging TEXT,
    marketing_name TEXT,
    exterior_color TEXT,
    wheel_type TEXT,
    spoiler_type TEXT,
    efficiency_kwh_per_km DOUBLE PRECISION,
    distance_unit TEXT,
    display_priority INTEGER,
    source TEXT NOT NULL DEFAULT 'fleet',
    external_id TEXT,
    inserted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX vehicles_external_idx
    ON vehicles (source, external_id)
    WHERE external_id IS NOT NULL;

CREATE TABLE vehicle_state (
    vehicle_id BIGINT PRIMARY KEY REFERENCES vehicles (id) ON DELETE CASCADE,
    activity TEXT NOT NULL CHECK (
        activity IN ('online', 'asleep', 'offline', 'driving', 'charging', 'updating')
    ),
    battery_level DOUBLE PRECISION,
    usable_battery_level DOUBLE PRECISION,
    rated_range_km DOUBLE PRECISION,
    ideal_range_km DOUBLE PRECISION,
    est_range_km DOUBLE PRECISION,
    odometer_km DOUBLE PRECISION,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    heading_deg DOUBLE PRECISION,
    speed_kmh DOUBLE PRECISION,
    power_kw DOUBLE PRECISION,
    inside_temp_c DOUBLE PRECISION,
    outside_temp_c DOUBLE PRECISION,
    climate_on BOOLEAN,
    locked BOOLEAN,
    sentry_mode BOOLEAN,
    charging_state TEXT,
    charger_power_kw DOUBLE PRECISION,
    charge_energy_added_kwh DOUBLE PRECISION,
    charge_limit_soc DOUBLE PRECISION,
    shift_state TEXT,
    is_dc BOOLEAN,
    software_version TEXT,
    update_status TEXT,
    last_poll_at TIMESTAMPTZ,
    last_data_at TIMESTAMPTZ,
    last_error TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    display_name TEXT,
    name TEXT,
    house_number TEXT,
    road TEXT,
    neighbourhood TEXT,
    city TEXT,
    county TEXT,
    state TEXT,
    state_district TEXT,
    postcode TEXT,
    country TEXT,
    osm_id BIGINT,
    osm_type TEXT,
    raw JSONB,
    cache_key TEXT,
    source TEXT NOT NULL DEFAULT 'nominatim',
    external_id TEXT,
    inserted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX addresses_cache_key_idx
    ON addresses (cache_key)
    WHERE cache_key IS NOT NULL;

CREATE UNIQUE INDEX addresses_external_idx
    ON addresses (source, external_id)
    WHERE external_id IS NOT NULL;

CREATE TABLE geofences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    radius_m DOUBLE PRECISION NOT NULL CHECK (radius_m > 0),
    billing_type TEXT,
    cost_per_unit DOUBLE PRECISION,
    session_fee DOUBLE PRECISION,
    source TEXT NOT NULL DEFAULT 'local',
    external_id TEXT,
    inserted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX geofences_external_idx
    ON geofences (source, external_id)
    WHERE external_id IS NOT NULL;

CREATE TABLE drives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ,
    start_latitude DOUBLE PRECISION,
    start_longitude DOUBLE PRECISION,
    end_latitude DOUBLE PRECISION,
    end_longitude DOUBLE PRECISION,
    start_odometer_km DOUBLE PRECISION,
    end_odometer_km DOUBLE PRECISION,
    distance_km DOUBLE PRECISION,
    duration_s INTEGER,
    start_battery_level DOUBLE PRECISION,
    end_battery_level DOUBLE PRECISION,
    start_rated_range_km DOUBLE PRECISION,
    end_rated_range_km DOUBLE PRECISION,
    start_ideal_range_km DOUBLE PRECISION,
    end_ideal_range_km DOUBLE PRECISION,
    energy_used_kwh DOUBLE PRECISION,
    max_speed_kmh DOUBLE PRECISION,
    avg_speed_kmh DOUBLE PRECISION,
    max_power_kw DOUBLE PRECISION,
    min_power_kw DOUBLE PRECISION,
    elevation_gain_m DOUBLE PRECISION,
    elevation_loss_m DOUBLE PRECISION,
    inside_temp_avg_c DOUBLE PRECISION,
    outside_temp_avg_c DOUBLE PRECISION,
    start_address_id BIGINT REFERENCES addresses (id) ON DELETE SET NULL,
    end_address_id BIGINT REFERENCES addresses (id) ON DELETE SET NULL,
    start_geofence_id BIGINT REFERENCES geofences (id) ON DELETE SET NULL,
    end_geofence_id BIGINT REFERENCES geofences (id) ON DELETE SET NULL,
    source TEXT NOT NULL DEFAULT 'poll',
    external_id TEXT
);

CREATE UNIQUE INDEX drives_external_idx
    ON drives (source, external_id)
    WHERE external_id IS NOT NULL;

CREATE UNIQUE INDEX drives_one_open_idx
    ON drives (vehicle_id)
    WHERE end_at IS NULL AND source = 'poll';

CREATE INDEX drives_vehicle_start_idx ON drives (vehicle_id, start_at DESC);

CREATE TABLE charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ,
    energy_added_kwh DOUBLE PRECISION,
    energy_used_kwh DOUBLE PRECISION,
    start_battery_level DOUBLE PRECISION,
    end_battery_level DOUBLE PRECISION,
    start_rated_range_km DOUBLE PRECISION,
    end_rated_range_km DOUBLE PRECISION,
    start_ideal_range_km DOUBLE PRECISION,
    end_ideal_range_km DOUBLE PRECISION,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    address_id BIGINT REFERENCES addresses (id) ON DELETE SET NULL,
    geofence_id BIGINT REFERENCES geofences (id) ON DELETE SET NULL,
    is_dc BOOLEAN,
    charger_type TEXT,
    max_power_kw DOUBLE PRECISION,
    duration_s INTEGER,
    cost DOUBLE PRECISION,
    outside_temp_avg_c DOUBLE PRECISION,
    source TEXT NOT NULL DEFAULT 'poll',
    external_id TEXT
);

CREATE UNIQUE INDEX charges_external_idx
    ON charges (source, external_id)
    WHERE external_id IS NOT NULL;

CREATE UNIQUE INDEX charges_one_open_idx
    ON charges (vehicle_id)
    WHERE end_at IS NULL AND source = 'poll';

CREATE INDEX charges_vehicle_start_idx ON charges (vehicle_id, start_at DESC);

CREATE TABLE charge_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_id BIGINT NOT NULL REFERENCES charges (id) ON DELETE CASCADE,
    recorded_at TIMESTAMPTZ NOT NULL,
    battery_level DOUBLE PRECISION,
    usable_battery_level DOUBLE PRECISION,
    charger_power_kw DOUBLE PRECISION,
    charger_voltage DOUBLE PRECISION,
    charger_current DOUBLE PRECISION,
    charge_energy_added_kwh DOUBLE PRECISION,
    ideal_range_km DOUBLE PRECISION,
    rated_range_km DOUBLE PRECISION,
    outside_temp_c DOUBLE PRECISION,
    source TEXT NOT NULL DEFAULT 'poll',
    external_id TEXT
);

CREATE UNIQUE INDEX charge_samples_moment_idx
    ON charge_samples (charge_id, recorded_at, source);

CREATE UNIQUE INDEX charge_samples_external_idx
    ON charge_samples (source, external_id)
    WHERE external_id IS NOT NULL;

CREATE SEQUENCE positions_id_seq;

CREATE TABLE positions (
    id BIGINT NOT NULL DEFAULT nextval('positions_id_seq'),
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    recorded_at TIMESTAMPTZ NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    speed_kmh DOUBLE PRECISION,
    power_kw DOUBLE PRECISION,
    odometer_km DOUBLE PRECISION,
    elevation_m DOUBLE PRECISION,
    battery_level DOUBLE PRECISION,
    usable_battery_level DOUBLE PRECISION,
    ideal_range_km DOUBLE PRECISION,
    rated_range_km DOUBLE PRECISION,
    est_range_km DOUBLE PRECISION,
    inside_temp_c DOUBLE PRECISION,
    outside_temp_c DOUBLE PRECISION,
    heading_deg DOUBLE PRECISION,
    drive_id BIGINT,
    charge_id BIGINT,
    source TEXT NOT NULL DEFAULT 'poll',
    external_id TEXT,
    PRIMARY KEY (id, recorded_at)
) PARTITION BY RANGE (recorded_at);

ALTER SEQUENCE positions_id_seq OWNED BY positions.id;

CREATE INDEX positions_vehicle_time_idx ON positions (vehicle_id, recorded_at);
CREATE INDEX positions_drive_time_idx ON positions (drive_id, recorded_at);
CREATE INDEX positions_charge_time_idx ON positions (charge_id, recorded_at);

CREATE UNIQUE INDEX positions_external_idx
    ON positions (source, external_id, recorded_at)
    WHERE external_id IS NOT NULL;

CREATE UNIQUE INDEX positions_poll_idx
    ON positions (vehicle_id, recorded_at, source)
    WHERE source = 'poll';

ALTER TABLE positions
    ADD CONSTRAINT positions_drive_fk
    FOREIGN KEY (drive_id) REFERENCES drives (id) ON DELETE SET NULL;

ALTER TABLE positions
    ADD CONSTRAINT positions_charge_fk
    FOREIGN KEY (charge_id) REFERENCES charges (id) ON DELETE SET NULL;

DO $$
DECLARE
    month_start date := DATE '2012-01-01';
    month_end date := DATE '2036-01-01';
    month_cursor date;
    part_name text;
BEGIN
    month_cursor := month_start;
    WHILE month_cursor < month_end LOOP
        part_name := 'positions_' || to_char(month_cursor, 'YYYY_MM');
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF positions FOR VALUES FROM (%L) TO (%L)',
            part_name,
            month_cursor,
            (month_cursor + INTERVAL '1 month')::date
        );
        month_cursor := (month_cursor + INTERVAL '1 month')::date;
    END LOOP;
END $$;

CREATE TABLE positions_default PARTITION OF positions DEFAULT;

