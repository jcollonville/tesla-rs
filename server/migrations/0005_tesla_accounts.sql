-- One Tesla account per row. Phase 1 imports the existing Fleet and Owner
-- token files into a single row of each kind. Later accounts reuse this table.
-- tokens is AES-GCM ciphertext (or plaintext JSON when no encryption key is set).
-- file_imported_at records that the on-disk file was already considered, so a
-- later disconnect does not reload the backup file.

CREATE TABLE tesla_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('fleet', 'owner')),
    tokens BYTEA,
    status TEXT NOT NULL DEFAULT 'unknown' CHECK (
        status IN ('unknown', 'connected', 'disconnected', 'error')
    ),
    last_refresh_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    file_imported_at TIMESTAMPTZ
);

CREATE INDEX tesla_accounts_kind_idx ON tesla_accounts (kind, id);

ALTER TABLE vehicles
    ADD COLUMN account_id BIGINT REFERENCES tesla_accounts (id) ON DELETE SET NULL;

CREATE INDEX vehicles_account_idx ON vehicles (account_id);
