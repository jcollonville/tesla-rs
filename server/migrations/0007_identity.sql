-- Console phase 2. Additive only: users, sessions, vehicle access, token scopes.
-- Existing api_tokens rows gain read + read:live and keep a null vehicle list,
-- which means no vehicle restriction. Bootstrap assigns them to the admin.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'user')),
    must_change_password BOOLEAN NOT NULL DEFAULT false,
    totp_secret BYTEA,
    totp_enabled BOOLEAN NOT NULL DEFAULT false,
    recovery_preview BYTEA,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE vehicle_access (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('owner', 'viewer')),
    PRIMARY KEY (user_id, vehicle_id)
);

CREATE TABLE sessions (
    id_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    sudo_until TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    last_vehicle_id BIGINT,
    ip TEXT
);

CREATE INDEX sessions_user_idx ON sessions (user_id, created_at DESC);

CREATE TABLE recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL,
    used_at TIMESTAMPTZ
);

CREATE TABLE login_throttle (
    subject TEXT PRIMARY KEY,
    failures INTEGER NOT NULL DEFAULT 0,
    next_at TIMESTAMPTZ,
    locked_until TIMESTAMPTZ
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    outcome TEXT NOT NULL,
    detail JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX audit_log_at_idx ON audit_log (at DESC);

ALTER TABLE api_tokens
    ADD COLUMN user_id BIGINT REFERENCES users (id) ON DELETE CASCADE,
    ADD COLUMN scopes TEXT[] NOT NULL DEFAULT ARRAY['read', 'read:live']::text[],
    ADD COLUMN expires_at TIMESTAMPTZ,
    ADD COLUMN vehicle_ids BIGINT[];

ALTER TABLE tesla_accounts
    ADD COLUMN paused_until TIMESTAMPTZ;

CREATE FUNCTION grant_admin_vehicle_access() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO vehicle_access (user_id, vehicle_id, role)
    SELECT users.id, NEW.id, 'owner'
    FROM users
    WHERE users.role = 'admin'
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END;
$$;

CREATE TRIGGER vehicles_grant_admin
    AFTER INSERT ON vehicles
    FOR EACH ROW
    EXECUTE FUNCTION grant_admin_vehicle_access();
