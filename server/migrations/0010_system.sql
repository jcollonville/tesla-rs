-- Geofence ownership and passkey storage. NULL owner_user_id means the fence is shared.

ALTER TABLE geofences
    ADD COLUMN owner_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL;

CREATE INDEX geofences_owner_idx ON geofences (owner_user_id);

CREATE TABLE passkeys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    credential_id BYTEA NOT NULL UNIQUE,
    passkey JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE passkey_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    state JSONB NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
